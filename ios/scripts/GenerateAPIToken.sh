#!/bin/bash
# Injects VOXERA_API_TOKEN into Generated/APIToken.generated.swift for Debug and Release/TestFlight.
# Source: build setting VOXERA_API_TOKEN and/or Voxera/Secrets.xcconfig (gitignored).
set -euo pipefail

ROOT="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
SECRETS="$ROOT/Voxera/Secrets.xcconfig"
OUT="$ROOT/Voxera/Generated/APIToken.generated.swift"
mkdir -p "$(dirname "$OUT")"

TOKEN="${VOXERA_API_TOKEN:-}"
if [[ -f "$SECRETS" ]]; then
  LINE=$(grep -E '^[[:space:]]*VOXERA_API_TOKEN[[:space:]]*=' "$SECRETS" | tail -1 || true)
  if [[ -n "${LINE}" ]]; then
    TOKEN=$(printf '%s' "$LINE" | sed 's/^[^=]*=[[:space:]]*//' | tr -d '\r' | sed 's/[[:space:]]*$//')
  fi
fi

# Strip accidental surrounding quotes
if [[ "${TOKEN}" =~ ^\".*\"$ ]]; then
  TOKEN="${TOKEN:1:${#TOKEN}-2}"
fi

TOKEN_ESC=$(printf '%s' "$TOKEN" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

cat > "$OUT" <<EOF
// Generated by scripts/GenerateAPIToken.sh — do not edit by hand.
enum APIToken {
  static let value: String = "${TOKEN_ESC}"
}
EOF

echo "note: GenerateAPIToken wrote APIToken.generated.swift (length=${#TOKEN})"

if [[ "${CONFIGURATION:-Debug}" == "Release" && -z "$TOKEN" ]]; then
  echo "error: VOXERA_API_TOKEN is empty for Release/TestFlight."
  echo "error: Create ios/Voxera/Secrets.xcconfig with: VOXERA_API_TOKEN = your_token"
  echo "error: Then Product → Clean Build Folder → Archive again."
  exit 1
fi
